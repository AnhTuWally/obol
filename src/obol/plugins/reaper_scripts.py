"""Pure-Lua ReaScript generators and REAPER toolbar menu exporter for Obol."""

from __future__ import annotations

OBOL_INTEGRATION_VERSION = "1.4"


def _lua_long_str(value: str) -> str:
    """Encodes an arbitrary string safely as a Lua long-bracket string."""
    eq = ""
    while f"]{eq}]" in value or f"[{eq}[" in value:
        eq += "="
    # If value starts with newline, Lua strips the first newline in [[...]], so prepend one if needed
    prefix = "\n" if value.startswith("\n") else ""
    return f"[{eq}[{prefix}{value}]{eq}]"


def render_obol_config_lua(
    python_exe: str,
    pythonw_exe: str,
    pythonpath: str,
    obol_home: str,
    bridge_dir: str,
    bridge_cmd_id: str,
) -> str:
    """Generates machine-local `Scripts/Obol/obol_config.lua`."""
    return "\n".join([
        "-- Auto-generated by Obol REAPER Installer. Do not edit manually.",
        "return {",
        f"  INTEGRATION_VERSION = {_lua_long_str(OBOL_INTEGRATION_VERSION)},",
        f"  PYTHON_EXE = {_lua_long_str(python_exe)},",
        f"  PYTHONW_EXE = {_lua_long_str(pythonw_exe)},",
        f"  PYTHONPATH = {_lua_long_str(pythonpath)},",
        f"  OBOL_HOME = {_lua_long_str(obol_home)},",
        f"  BRIDGE_DIR = {_lua_long_str(bridge_dir)},",
        f"  BRIDGE_CMD_ID = {_lua_long_str(bridge_cmd_id)},",
        "}",
        "",
    ])


